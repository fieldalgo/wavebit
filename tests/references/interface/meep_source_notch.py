"""Generate a source-notch control using Meep's documented public API only.

No external implementation is inspected or imported by ordinary tests.
API: https://meep.readthedocs.io/en/latest/Python_User_Interface/#customsource
"""
import argparse
import sys
import warnings

sys.tracebacklimit = 0
warnings.simplefilter('ignore')

import numpy as np


def generate():
    import meep as mp
    mp.verbosity(0)
    dt, epsilon, omega0, strength, width = .04, 2., 3., 2., 5.
    frequency = np.arcsin(dt*np.sqrt(omega0**2+strength/epsilon)/2)/(np.pi*dt)
    phase = np.exp(-2j*np.pi*frequency*dt)
    def gaussian(t):
        return (np.exp(-((t-5*width)/width)**2)*np.exp(-2j*np.pi*frequency*t)
                if 0 <= t <= 10*width else 0j)
    def difference(t):
        return gaussian(t)-phase*gaussian(t-dt)
    sample_t = (np.arange(int(np.ceil((10*width+dt)/dt)))+.5)*dt
    scale = max(abs(difference(t)) for t in sample_t)
    data = dict(meep_version=mp.__version__, dt=dt, epsilon=epsilon, omega0=omega0,
                strength=strength, width=width, frequency=frequency, filtered_peak=scale)
    for name, waveform in (('gaussian', gaussian), ('notched', lambda t: difference(t)/scale)):
        medium = mp.Medium(epsilon=epsilon, E_susceptibilities=[mp.LorentzianSusceptibility(
            frequency=omega0/(2*np.pi), gamma=0., sigma=strength/omega0**2)])
        size = mp.Vector3(.4, .4, .4)
        simulation = mp.Simulation(cell_size=size, resolution=10, Courant=.4,
                                   k_point=mp.Vector3(), force_complex_fields=True,
                                   default_material=medium, sources=[mp.Source(
                                       mp.CustomSource(waveform, start_time=0., end_time=10*width+dt),
                                       mp.Ey, mp.Vector3(), size=size)])
        times, signals = [], []
        def record(s):
            times.append(s.meep_time())
            signals.append(s.get_field_point(mp.Ey, mp.Vector3()))
        simulation.run(mp.after_sources(mp.at_every(.08, record)), until_after_sources=10.)
        data[name+'_t'], data[name+'_signal'] = np.array(times), np.array(signals)
        simulation.reset_meep()
    return data


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, help='Destination npz archive; generated by hand only.')
    args = parser.parse_args()
    np.savez_compressed(args.output, **generate())
