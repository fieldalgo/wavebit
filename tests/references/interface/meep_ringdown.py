"""Generate source-free traces using only Meep's documented public API.

Run by hand in a Meep environment; not imported by Wavebit or ordinary tests.
No Meep or Harminv implementation is read, copied or bundled.
Public API: https://meep.readthedocs.io/en/latest/Python_User_Interface/
"""
import argparse
import sys
import warnings

sys.tracebacklimit = 0
# Suppress automatic source-line excerpts from external runtime warnings.
warnings.simplefilter('ignore')

import numpy as np


def generate():
    import meep as mp
    mp.verbosity(0)
    data = dict(meep_version=mp.__version__, epsilon=2., gamma=.1, courant=.4,
                omega0=3., strength=2., record_interval=.08, after_sources=40.)
    for name, resolution, length, frequency in (('lorentz', 10, .4, .5), ('cavity', 20, 1., .7)):
        if name == 'lorentz':
            medium = mp.Medium(epsilon=2., E_susceptibilities=[mp.LorentzianSusceptibility(
                frequency=3/(2*np.pi), gamma=.1/(2*np.pi), sigma=2/9)])
            pattern = lambda point: 1.
        else:
            medium = mp.Medium(epsilon=2., D_conductivity=.1)
            pattern = lambda point: np.cos(2*np.pi*point.z)
        size = mp.Vector3(.4, .4, length)
        sim = mp.Simulation(
            cell_size=size, resolution=resolution, Courant=.4, k_point=mp.Vector3(),
            default_material=medium, sources=[mp.Source(
                mp.GaussianSource(frequency, fwidth=.3, cutoff=4), mp.Ey, mp.Vector3(),
                size=size, amp_func=pattern)])
        times, values = [], []
        def record(s):
            times.append(s.meep_time())
            values.append(s.get_field_point(mp.Ey, mp.Vector3()))
        sim.run(mp.after_sources(mp.at_every(.08, record)), until_after_sources=40.)
        data.update({name+'_t': np.asarray(times), name+'_signal': np.asarray(values),
                     name+'_dt': .4/resolution, name+'_dx': 1/resolution,
                     name+'_length': length})
        sim.reset_meep()
    return data


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, help='Destination npz archive; generated by hand only.')
    args = parser.parse_args()
    np.savez_compressed(args.output, **generate())
