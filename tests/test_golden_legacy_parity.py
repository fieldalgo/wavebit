"""Pinned reference results, captured from the legacy solver before it was replaced.

The core was proven against the legacy transfer-matrix chains by direct comparison while both
were live. Now that ``solve`` dispatches into the core, comparing the two in-process would
be self-referential — so the legacy numbers are frozen in ``golden_legacy.npz`` (generated by
``gen_goldens.py`` against commit 37ed0da, the last one where ``_BaseRCWA`` still used
``transfer_method``).

This is the oracle that outlives the legacy code: it keeps working after the triplicated
backends are deleted, and it covers the whole public result surface — efficiencies,
amplitudes, the TE/TM incidence variants, and the ``layer_info_list`` / ``T1`` state that field
reconstruction reads.

Two rounds of entries are no longer legacy-derived.

``2d_cfs`` exercised the integrated builder, which read the raster's first row as the *last* y
while the sampled and NVF builders read it as the first -- so the frozen values were the answer to the mirrored
structure, and no transform recovers them. Those entries were recomputed after the axis was
unified (2026-08-05), checked against Reticolo rather than against this implementation: pure TE
and TM incidence on that exact structure agree to 7e-14.

Then every entry was recomputed (2026-08-05) when the sampled builder stopped resampling the
raster. It used to upsample each layer until the grid resolved ``4*truncation_order+1`` harmonics and
transform that, which approaches the raster's own Fourier coefficients as ``1/R``; those are
now computed exactly instead, which moved the answers by ~1e-5. The legacy values encoded the
approximation, so keeping them would have pinned it. Six of the thirteen cases were checked
against Reticolo before refreezing and agree to ~1e-14: te/tm_1layer, te/tm_oblique,
te_2layer, te_same_mat. The two conical cases use a mixed ``psi`` that Reticolo's conical
branch has no counterpart for (driven by TE or TM incidence, nothing between) -- the same
structures at ``psi = pi/2`` and ``psi = 0`` agree to 2e-15. The five 2D cases have no
independent check here; ``test_reticolo_golden`` is the standing one, on its own cases.

Then ``2d_nvf`` alone was recomputed (2026-08-07) when the NVF path stopped over-refining the
grid its normal field is taken on. It used to repeat each cell ``4*truncation_order+1`` times before the
distance transform; it now lifts a layer only to the floor that transform needs, which on this
5x5 case is a 10x10 grid rather than 50x50. The answer moves a lot -- transmitted efficiency
0.684 to 0.352 under TM incidence -- and energy is conserved to 1.000000000000 either way.
There is no independent oracle for a *random* 5x5 raster under NVF, and there cannot really be
one: NVF's premise is that a staircase stands for a smooth boundary, and a random raster has no
boundary behind it. The justification is elsewhere -- on smooth shapes, where an analytic
reference exists, the over-refined grid was worse in 27 of 32 combinations
(``docs/nvf-upsampling.md``).

What that costs is worth naming: for those seven, and now for ``2d_nvf`` a second time, this
file pins continuity against this implementation rather than against the one it replaced.

Then on 2026-08-16 ``2d_nvf`` left this file altogether, into ``data/golden_nvf.npz`` with a
generator of its own. Not a third recomputation dressed up: ``gen_goldens.py`` refuses to run,
and rightly, because re-freezing the legacy file against today's solver would convert the
repo's only legacy-parity evidence into a change detector with every test still green. The
prescribed route out is the one ``test_field_core.py`` took for the 2026-08-14 sign fix --
retire the entry and re-freeze it once, under a name that stops claiming legacy provenance. So
``golden_legacy.npz`` is untouched, byte-identical, and the twelve cases in it are still what
this file's title says they are. The occasion was the half-pixel cell-centre phase missing from
the sampled transform (``_half_pixel_phase``); the evidence that the new values are the better
ones is quadrature order, not this file, and ``gen_goldens_nvf.py`` carries it.

A change the same week needed **no** recomputation at all, and that distinction is the one to
keep. The per-order s/p frame was reversed on the ``Re(kx) < 0`` half-plane, in the legacy
solver and in the rewrite alike (``docs/amplitude-sp-frame.md``); fixing it moved the complex
amplitudes of the seven coupled cases by a sign on those orders and left all six efficiencies
of all thirteen untouched, since a half-turn cannot survive ``|r|**2``. That is a *convention*
difference between the frozen numbers and today's, exactly like the ``H -> E`` factors already
in :func:`_amp_map`, so it is applied as one -- see :func:`_frame_sign`. Both ``.npz`` files
stay byte-identical, including the one frozen days earlier, which is the strongest available
statement that nothing here was re-frozen to make a test pass. The move of every amplitude's
lateral phase reference from the cell corner to its centre (2026-09-27) is a third such
convention, :func:`_centre_sign`, and was handled the same way.

Compared to ``atol=1e-12``, not bit-for-bit. Bit-exactness was the right test while the port
was being *proved* equal to the legacy chain; as a standing guard it fails on things that are
not defects — reassociating a sum moves the last digit (``(a-b)-c`` and ``a-(b+c)`` differ by
~1e-16), and so can a different BLAS. It also pushes back on legitimate cleanups, which is the
opposite of what an oracle should do. Every real defect this file exists to catch is orders of
magnitude larger: the boundary-convention bugs found in 2026-08 ran from 1% to 4900%.
"""
import pathlib

import numpy as np
import pytest

import wavebit

# Tight enough that no defect hides under it, loose enough to ignore float reassociation.
TOL = 1e-12

_DATA = pathlib.Path(__file__).parent / 'data'


class _Goldens:
    """``golden_legacy.npz``, with ``2d_nvf`` served from its own self-captured file.

    Twelve cases are legacy-derived and stay in the legacy file, byte-identical. ``2d_nvf`` is
    not, and has not been since 2026-08-07; keeping it there let one file carry two provenances
    under a name that claimed only the stronger one. It now lives in ``golden_nvf.npz``, written
    by a generator that *runs* and states what it captures -- while ``gen_goldens.py`` goes on
    refusing, which is what protects the twelve.

    Reading is one lookup either way, and the entries share a schema, so nothing downstream
    branches on which file an array came from -- a case cannot be compared more loosely just by
    moving house.
    """

    def __init__(self):
        self._legacy = np.load(_DATA / 'golden_legacy.npz')
        self._nvf = np.load(_DATA / 'golden_nvf.npz')

    def __getitem__(self, key):
        return self._nvf[key] if key.startswith('2d_nvf__') else self._legacy[key]

    def __contains__(self, key):
        return key in (self._nvf if key.startswith('2d_nvf__') else self._legacy)


GOLDEN = _Goldens()

# The golden stores the legacy field layout: efficiencies as R/T and the raw
# *boundary* amplitudes as R_s..T_p. The 2026-08-12 result rename kept every efficiency
# value and moved the amplitudes to Fresnel normalization, so the map from a golden entry
# to today's attribute carries a conversion factor for the amplitudes. The factors are the
# exact ones the pack sites apply (measured against the Airy forms in test_lossy_media),
# so applying them to the golden reproduces today's stored values to float rounding —
# nothing here was regenerated.
#
#   golden key   attr    pure-1D path            coupled (conical / 2D) path
EFFICIENCIES = (('de_ri', 'R'), ('de_ri_s', 'R_s'), ('de_ri_p', 'R_p'),
                ('de_ti', 'T'), ('de_ti_s', 'T_s'), ('de_ti_p', 'T_p'))

# The third axis of the same translation, added 2026-08-20 when `Result.res` /
# `.res_te_inc` / `.res_tm_inc` became `.incident` / `.s_inc` / `.p_inc`. The golden's key
# component is the *legacy* attribute name, and it stays that way for the same reason
# `de_ri` above does: `golden_legacy.npz` cannot be recaptured -- the implementation that
# produced it was deleted -- so its keys are a record of what that implementation called
# things, and `gen_goldens.py`'s own note prescribes transforming AT THE COMPARISON rather
# than rewriting the file. `golden_nvf.npz` follows it rather than diverging: one reader,
# one key vocabulary.
#
#   golden key component   today's attribute
SUBS = (('res', 'incident'), ('res_te_inc', 's_inc'), ('res_tm_inc', 'p_inc'))


def _amp_map(grating_type, n_top, n_bot):
    if grating_type == 0:                              # pure 1D: primary is the amplitude
        return (('R_s', 'r_s', 1.0), ('R_p', 'r_p', 1.0),
                ('T_s', 't_s', 1.0), ('T_p', 't_p', n_top / n_bot))
    return (('R_s', 'r_s', 1.0), ('R_p', 'r_p', 1.0 / (-1j * n_top)),   # coupled: H -> E
            ('T_s', 't_s', 1.0), ('T_p', 't_p', 1.0 / (-1j * n_bot)))


def _frame_sign(solver, grating_type):
    """The second convention conversion the amplitudes need: a per-order ``+-1``.

    The legacy solver built each order's s/p frame as ``atan(ky/kx)``, which reads a ratio and
    so cannot see ``sign(kx)``; every order with ``Re(kx) < 0`` came back in ``-s_hat``,
    ``-p_hat``. That was carried into the rewrite unchanged and fixed in
    :func:`~wavebit._core.conventions.order_azimuth` (see ``docs/amplitude-sp-frame.md``), so
    the frozen amplitudes are in the old frame on that half-plane and today's are not.

    A conversion rather than a regeneration, and the distinction matters here. The factors in
    :func:`_amp_map` exist because the golden stores *legacy* values in the *legacy*
    convention; this is one more of those, and it keeps the frozen magnitudes and phases
    exactly as the run that produced them left them instead of refreezing anything from the
    implementation under test. It is closed-form and checkable by hand -- ``kx`` is
    ``n_top*sin(theta)*cos(phi) + m*wl/Px``, read here off the solver's geometry so no
    formula is restated, and nothing about the amplitude path is consulted.

    Applied to ``2d_nvf`` as well, on the same grounds and not by oversight. That case is
    self-captured rather than legacy-derived, and its generator *runs* -- so re-freezing it
    was available and was not taken. It was captured before the fix, which puts it in the old
    frame exactly like the twelve; converting keeps ``golden_nvf.npz`` byte-identical to the
    freeze that ``gen_goldens_nvf.py`` documents, whose stated reason was the half-pixel
    phase and nothing else. Two re-freezes in one week for unrelated reasons would leave that
    record unreadable.

    A half-turn cancels in ``|r|**2``, so the efficiency comparisons above are untouched and
    stay a pure legacy check.

    **The six pure-1D cases joined on 2026-09-27**, for the same kind of reason. Until then the
    pure TE/TM path quoted its Cartesian primary (``E_y`` / ``H_y``) on every order and these
    cases got ``1``; it now quotes each order in its own s/p frame like the coupled paths,
    which on the ``ky == 0`` row is ``s_hat = sign(Re kx) * y_hat``. So the frozen 1D
    amplitudes are the new ones times ``sigma_m * sigma_inc`` -- ``sigma_inc`` because a frozen
    solve lit by ``+y`` answered, on an incident order with ``kx < 0``, the negative of the
    field today's is lit with. The same spelling serves every case: ``sigma_inc`` is read at
    the specular index, and it is ``+1`` for all thirteen (every ``theta`` here is ``>= 0``),
    so the coupled conversion is the one it was, and nothing was re-frozen.
    """
    kx = np.real(np.asarray(solver.order_kxy()[0], dtype=np.complex128)).ravel()
    sigma = np.where(kx < 0, -1.0, 1.0)
    return np.reshape(sigma * sigma[kx.size // 2], (1, -1))


def _centre_sign(result):
    """The third conversion, and also a per-order ``+-1``: the lateral phase reference.

    The legacy solver -- like this one's kernels today -- referenced every amplitude at the cell
    **corner**, its Fourier origin; since 2026-09-27 every public amplitude is referenced at the
    cell **centre** ``o = (a1 + a2)/2``, the origin every public coordinate uses. Against the
    centre, order ``(m, n)`` carries ``exp(1j * k_mn . o)``, which is the specular order's
    ``exp(1j * k_inc . o)`` times ``(-1)**(m + n)``, because ``b_i . a_j = 2 pi delta_ij``. The
    common factor cancels between the amplitude and the unit incident wave it is a ratio
    against, so the frozen amplitudes are today's times ``(-1)**(m + n)``.

    Spelled from the result's own order **labels** (``orders_u`` / ``orders_v``), not from the
    solver's window arithmetic and not from the engine's helper, so this stays a statement about
    the golden rather than a restatement of the code under test. Every case here keeps the
    default window, centred on the specular order. Closed-form, exact, and it cancels in
    ``|r|**2``, like the two conversions before it: the efficiency comparisons are untouched.
    """
    m, n = np.asarray(result.orders_u), np.asarray(result.orders_v)
    return np.where((n[:, None] + m[None, :]) % 2 == 1, -1.0, 1.0)


def _rand(shape, seed):
    """The same raster the generator drew, restated as PERMITTIVITY.

    The draw is unchanged and the square is what the solver used to apply on the way in, so
    every case below is bit-for-bit the structure the frozen run solved. That is the whole
    constraint here: these numbers were captured from a solver that no longer exists, so the
    scene handed to today's API has to be the same scene, not merely a similar one.
    """
    return np.random.default_rng(seed).uniform(1.0, 4.0, size=shape) ** 2


