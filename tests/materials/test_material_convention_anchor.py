"""Which material quantity the public API takes, pinned against closed-form Fresnel.

Wavebit takes a **relative permittivity** at the front door -- ``structure``, ``top``, ``bot``,
and the shape material slots -- and hands it to the factorization unconverted. That
is a convention, not a fact, and until the migration of 2026-08-20 it was the other one: the
API took a refractive index and squared it on the way in
(``_core.factorization._layer_eps``), which left the package holding two conventions at once --
``solve_conv`` and the tensor builders took permittivity, ``mu`` was taken raw, and
``domain.Layer.eps`` was named for permittivity while holding an index. The flip removed that
seam. What this file pins is that the flip happened *here*, in the one function that names the
convention, rather than being routed around it.

This file exists so that changing the convention cannot happen quietly. It is the anchor the
migration was measured against, and it has one property nothing else in the suite has: **its
expected numbers are derived from the physics, not from this implementation.** Every golden in
``tests/fixtures/legacy_rcwa`` is regenerated by a script that imports wavebit, so a convention flip that also
touches the generator produces a golden that agrees with the flipped code — a co-migrated
oracle confirms a co-migrated bug. Closed-form Fresnel cannot be co-migrated.

The single place that knows the convention is :func:`_api_material`, and it is now the
identity. The flip was exactly that one edit: **not one expected value in this file moved.**
That is the evidence the new convention is the same physics said differently rather than a
different answer -- and it is also why the flip could not be faked. Had the function been left
as a square root while the package moved, or moved while a literal elsewhere did not, the
numbers below would separate by far more than any tolerance: the same literal ``3.5`` read as
an index gives ``R = 0.3086`` and read as a permittivity gives ``R = 0.0920``, and both
conserve energy exactly, so nothing else in the suite can tell them apart.

Uniform layers at ``truncation_order=0`` throughout: only the zeroth order exists, so the solver is being
asked the multilayer question the Fresnel/Airy recursion answers, and any disagreement is
about the material convention rather than about truncation. ``tests/rcwa/test_lossy_media.py``
carries the same oracle for a different purpose (the conjugation seam); this file is narrower
and deliberately duplicates a little of it, because the property being pinned is one an
unrelated edit to that file could drop.
"""

from wavebit.compat import legacy as _legacy_wavebit
import numpy as np
import pytest



def _api_material(eps):
    """The material spelling the public API takes, given a permittivity.

    THE ONE PLACE IN THIS FILE THAT KNOWS THE CONVENTION. The API now takes relative
    **permittivity**, so this is the identity: every physical quantity below was already stated
    as a permittivity -- which is what the solver works in and what the closed forms are
    written against -- and there is nothing left to convert.

    It stays as a function rather than being inlined away, because that is what makes the
    anchor an anchor. The whole file is written so that one edit here is the entire migration,
    and the expected values below are derived from Fresnel/Airy rather than from wavebit, so
    they cannot be co-migrated into agreement with a flip that went wrong. Deleting the hook
    would leave the numbers pinned but the convention unnamed, and the next flip would have
    nowhere to land.

    Before the flip this was ``np.sqrt(np.asarray(eps, dtype=complex))``, and the square root
    is the thing that went away: converting an index to a permittivity is unambiguous, while
    the other direction is a branch choice, and the half-space root is on this project's
    standing list of traps. It survives as :func:`wavebit.refractive_index_from_eps` for callers
    that genuinely need an index, where the branch is argued once instead of at every call site.
    """
    return eps


# Permittivities, stated as permittivities regardless of what the API takes. Silicon-like at
# 500 nm, silica-like, and one absorber whose loss is large enough that a conjugation error
# would show but small enough that the stack is not opaque.
EPS_AIR = 1.0
EPS_SI = 12.25          # n = 3.5
EPS_GLASS = 2.25        # n = 1.5
EPS_LOSSY = 4.0 + 0.8j


def _solve(eps_stack, thickness, eps_top, eps_bot, *, theta=0.0, tetm='te', wavelength=500.0):
    """Adapt the unchanged top-down Fresnel case to the bottom-up public API."""
    structure = np.array([[[complex(_api_material(e))]] for e in reversed(eps_stack)]) if eps_stack \
        else np.zeros((0, 1, 1), dtype=complex)
    solver = _legacy_wavebit.rcwa(
        backend='numpy', wavelength=wavelength, period=[300.], truncation_order=[0, 0],
        top=complex(_api_material(eps_top)), bot=complex(_api_material(eps_bot)),
        theta=theta, phi=0., tetm=tetm,
        structure=structure if len(eps_stack) else np.array([[[_api_material(EPS_AIR)]]]),
        thickness=list(reversed(thickness)) if len(thickness) else [0.],
    )
    res = solver.solve()
    return complex(np.asarray(res.R).sum()), complex(np.asarray(res.T).sum())


# ----------------------------------------------------------------- closed-form oracle

def _kz(eps, kx):
    """Longitudinal wavenumber over ``k0`` in a medium of permittivity ``eps``."""
    return np.sqrt(np.asarray(eps, dtype=complex) - kx ** 2)


def _fresnel_interface(eps_1, eps_2, kx, tetm):
    """Amplitude reflection at one interface, in the (kz, eps) form that has no index in it."""
    kz1, kz2 = _kz(eps_1, kx), _kz(eps_2, kx)
    if tetm == 'te':
        return (kz1 - kz2) / (kz1 + kz2)
    return (eps_2 * kz1 - eps_1 * kz2) / (eps_2 * kz1 + eps_1 * kz2)


def _airy_reflectance(eps_stack, thickness, eps_top, eps_bot, kx, tetm, wavelength):
    """Reflectance of a uniform stack by the standard bottom-up recursion.

    Written entirely in permittivity and ``kz`` -- there is no refractive index anywhere in
    this function, which is the point: the oracle cannot inherit the convention under test.
    """
    k0 = 2 * np.pi / wavelength
    r = _fresnel_interface(eps_stack[-1] if eps_stack else eps_top, eps_bot, kx, tetm) \
        if eps_stack else _fresnel_interface(eps_top, eps_bot, kx, tetm)
    for i in range(len(eps_stack) - 1, -1, -1):
        eps_above = eps_stack[i - 1] if i > 0 else eps_top
        r_i = _fresnel_interface(eps_above, eps_stack[i], kx, tetm)
        phase = np.exp(2j * k0 * _kz(eps_stack[i], kx) * thickness[i])
        r = (r_i + r * phase) / (1 + r_i * r * phase)
    return abs(r) ** 2


# ----------------------------------------------------------------- the anchor

CASES = [
    # (name, eps_stack, thickness, eps_top, eps_bot, theta_deg, tetm)
    ('bare interface, normal, TE', [], [], EPS_AIR, EPS_SI, 0.0, 'te'),
    ('bare interface, normal, TM', [], [], EPS_AIR, EPS_SI, 0.0, 'tm'),
    ('bare interface, 40 deg, TE', [], [], EPS_AIR, EPS_SI, 40.0, 'te'),
    ('bare interface, 40 deg, TM', [], [], EPS_AIR, EPS_SI, 40.0, 'tm'),
    ('one film on glass, normal, TE', [EPS_SI], [80.], EPS_AIR, EPS_GLASS, 0.0, 'te'),
    ('one film on glass, 30 deg, TM', [EPS_SI], [80.], EPS_AIR, EPS_GLASS, 30.0, 'tm'),
    ('two films, 20 deg, TE', [EPS_SI, EPS_GLASS], [60., 110.], EPS_AIR, EPS_SI, 20.0, 'te'),
    ('absorbing film, normal, TE', [EPS_LOSSY], [90.], EPS_AIR, EPS_GLASS, 0.0, 'te'),
]


@pytest.mark.parametrize('name,eps_stack,thickness,eps_top,eps_bot,theta_deg,tetm',
                         CASES, ids=[c[0] for c in CASES])
def test_the_api_material_is_the_one_this_file_declares(
        name, eps_stack, thickness, eps_top, eps_bot, theta_deg, tetm):
    """The solver's reflectance must match the closed form for the declared permittivities.

    Reading the same literals in the other convention moves these by 10-70%, so the tolerance
    is not what makes this test discriminating -- the two answers are nowhere near each other.
    It is tight anyway because a uniform stack at ``truncation_order=0`` is exactly the problem the
    recursion solves.
    """
    theta = np.deg2rad(theta_deg)
    wavelength = 500.0
    kx = np.sqrt(np.asarray(eps_top, dtype=complex)).real * np.sin(theta)

    got, _ = _solve(eps_stack, thickness, eps_top, eps_bot, theta=theta, tetm=tetm,
                    wavelength=wavelength)
    want = _airy_reflectance(eps_stack, thickness, eps_top, eps_bot, kx, tetm, wavelength)
    np.testing.assert_allclose(got.real, want, rtol=1e-10, atol=1e-12)


def test_the_other_convention_is_a_different_answer_and_not_a_tolerance():
    """The two readings of one literal are far apart, and both conserve energy.

    This is the reason the file exists, asserted rather than described. Without it a reader
    could reasonably assume a convention flip would surface as a tolerance failure somewhere;
    it would not surface at all. ``12.25`` read as an index is a medium of permittivity 150,
    which is perfectly legal and perfectly wrong.
    """
    kx = 0.0
    as_declared = _airy_reflectance([], [], EPS_AIR, EPS_SI, kx, 'te', 500.0)
    misread = _airy_reflectance([], [], EPS_AIR, EPS_SI ** 2, kx, 'te', 500.0)

    # (1 - 3.5)/(1 + 3.5) squared, against (1 - 12.25)/(1 + 12.25) squared
    assert as_declared == pytest.approx(0.30864197530864, rel=1e-12)
    assert misread == pytest.approx(0.72089711641153, rel=1e-12)
    assert abs(as_declared - misread) > 0.41

    # and the misreading is a legal, energy-conserving problem, so nothing else would catch it
    got, transmitted = _solve([], [], EPS_AIR, EPS_SI ** 2, theta=0.0, tetm='te')
    assert got.real + transmitted.real == pytest.approx(1.0, abs=1e-12)


def test_the_convention_marker_is_reachable_and_states_todays_answer():
    """``_api_material`` is the anchor's single edit point; keep it honest about today.

    Today it is the identity, because the API takes the permittivity every value in this file
    is already stated in. That reads like a tautology and is not one: it is the assertion that
    fired when the package flipped -- exactly as its previous wording predicted, since it then
    demanded ``sqrt`` -- and rewriting it *here* is what records that the migration went
    through the marker instead of past it. A move in either direction has to come back to this
    function, and this test is what stops that happening without a diff to point at.

    The complex case is asserted alongside the reals because the identity's whole content is
    that no branch is taken any more. A half-restored ``sqrt`` on the complex path only --
    where the branch actually costs something -- would leave both real assertions green.
    """
    assert _api_material(4.0) == pytest.approx(4.0)
    assert _api_material(EPS_SI) == pytest.approx(12.25)
    assert _api_material(EPS_LOSSY) == pytest.approx(4.0 + 0.8j)
