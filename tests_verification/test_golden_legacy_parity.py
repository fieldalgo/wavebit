"""Pinned reference results, captured from the legacy solver before it was replaced.

The core was proven against the legacy transfer-matrix chains by direct comparison while both
were live. Now that ``conv_solve`` dispatches into the core, comparing the two in-process would
be self-referential — so the legacy numbers are frozen in ``golden_legacy.npz`` (generated by
``gen_goldens.py`` against commit 37ed0da, the last one where ``_BaseRCWA`` still used
``transfer_method``).

This is the oracle that outlives the legacy code: it keeps working after the triplicated
backends are deleted, and it covers the whole public result surface — efficiencies,
amplitudes, the TE/TM incidence variants, and the ``layer_info_list`` / ``T1`` state that field
reconstruction reads.

One case is no longer legacy-derived. ``2d_cfs`` exercised the CFS builder, which read the
``ucell``'s first row as the *last* y while DFS and NVF read it as the first -- so the frozen
values are the answer to the mirrored structure, and no transform recovers them. Those entries
were recomputed after the axis was unified (2026-08-05), and the replacement is checked against
Reticolo rather than against this implementation: pure TE and TM incidence on that exact
structure agree to 7e-14. Every other case is still the legacy solver's own output.

Compared to ``atol=1e-12``, not bit-for-bit. Bit-exactness was the right test while the port
was being *proved* equal to the legacy chain; as a standing guard it fails on things that are
not defects — reassociating a sum moves the last digit (``(a-b)-c`` and ``a-(b+c)`` differ by
~1e-16), and so can a different BLAS. It also pushes back on legitimate cleanups, which is the
opposite of what an oracle should do. Every real defect this file exists to catch is orders of
magnitude larger: the boundary-convention bugs found in 2026-08 ran from 1% to 4900%.
"""
import pathlib

import numpy as np
import pytest

import fieldwave

# Tight enough that no defect hides under it, loose enough to ignore float reassociation.
TOL = 1e-12

GOLDEN = np.load(pathlib.Path(__file__).parent / 'golden_legacy.npz')
FIELDS = ('R_s', 'R_p', 'T_s', 'T_p',
          'de_ri', 'de_ri_s', 'de_ri_p', 'de_ti', 'de_ti_s', 'de_ti_p')


