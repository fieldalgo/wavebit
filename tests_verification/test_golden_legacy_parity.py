def _run(name):
    kw = dict(CASES[name])
    kw['ucell'] = np.asarray(kw['ucell'], dtype=float)
    solver = fieldwave.rcwa(backend=0, **kw)
    return solver, solver.conv_solve()


@pytest.mark.parametrize('name', list(CASES))
def test_results_match_legacy_golden(name):
    solver, result = _run(name)
    assert solver.grating_type_assigned == GOLDEN[f'{name}__grating_type']

    checked = 0
    for sub in ('res', 'res_te_inc', 'res_tm_inc'):
        got_sub = getattr(result, sub)
        if got_sub is None:
            assert f'{name}__{sub}__de_ri' not in GOLDEN, f'{sub} was present in the legacy run'
            continue
        for f in FIELDS:
            want = GOLDEN[f'{name}__{sub}__{f}']
            got = np.asarray(getattr(got_sub, f))
            assert np.allclose(want, got, atol=TOL, rtol=0), (
                sub, f, np.max(np.abs(want - got)))
            checked += 1
    assert checked >= 10


@pytest.mark.parametrize('name', list(CASES))
def test_field_reconstruction_state_is_a_valid_mode_basis(name):
    """``layer_info_list`` holds the per-layer modes ``calculate_field`` propagates.

    Compares only what is *defined*. An eigendecomposition fixes each mode's constant up to
    sign and each eigenvector up to scale, phase and ordering, so ``W`` / ``V`` / ``q`` / the
    transfer blocks are gauge, not data: the 2026-08 convention change moved every one of them
    while leaving the physics identical. What survives that freedom is the *set* of ``|q|``,
    which is what this checks, plus the per-layer permittivity block, which is not gauge at
    all.

    The reconstruction itself is pinned by ``test_field_matches_legacy_golden`` against the
    legacy field values — that is the test that would fail if this state were wrong.
    """
    solver, _ = _run(name)
    assert np.asarray(solver.T1).shape == GOLDEN[f'{name}__T1'].shape

    for i, layer in enumerate(solver.layer_info_list):
        epz_i, W, V, q = (np.asarray(layer[j]) for j in range(4))
        want_epz = GOLDEN[f'{name}__layer{i}__epz_i']
        assert np.allclose(want_epz, epz_i, atol=TOL, rtol=0), (
            i, 'epz_i', np.max(np.abs(want_epz - epz_i)))

        want_q = np.sort(np.abs(GOLDEN[f'{name}__layer{i}__q']))
        assert np.allclose(want_q, np.sort(np.abs(q)), atol=1e-10, rtol=0), (
            i, 'q', np.max(np.abs(want_q - np.sort(np.abs(q)))))

        assert W.shape == GOLDEN[f'{name}__layer{i}__W'].shape
        assert V.shape == GOLDEN[f'{name}__layer{i}__V'].shape
        assert float(layer[4]) == float(GOLDEN[f'{name}__layer{i}__d'])


def test_calculate_field_still_runs():
    """Smoke-cover field reconstruction end to end — it reads the state pinned above."""
    solver, _ = _run('2d_oblique')
    field = solver.calculate_field(res_x=4, res_y=4, res_z=4)
    field = np.asarray(field)
    assert field.ndim >= 3 and np.isfinite(field).all()


# ------------------------------------------------ every backend, one implementation

@pytest.mark.parametrize('backend', [1, 2], ids=['jax', 'torch'])
@pytest.mark.parametrize('name', list(CASES))
def test_jax_and_torch_match_the_same_golden(name, backend):
    """JAX and PyTorch run the same core, so they land on the NumPy reference too.

    This is the property the rewrite exists to guarantee: one implementation, so a backend
    cannot silently drift. The tolerance is float-rounding only — the backends' linear algebra
    differs in accumulation order, not in the physics.
    """
    pytest.importorskip('jax' if backend == 1 else 'torch')
    kw = dict(CASES[name])
    kw['ucell'] = np.asarray(kw['ucell'], dtype=float)
    result = fieldwave.rcwa(backend=backend, **kw).conv_solve()

    for sub in ('res', 'res_te_inc', 'res_tm_inc'):
        got_sub = getattr(result, sub)
        if got_sub is None:
            continue
        for f in ('de_ri', 'de_ti'):
            want = GOLDEN[f'{name}__{sub}__{f}']
            got = np.asarray(getattr(got_sub, f))
            assert np.allclose(want, got, atol=1e-12, rtol=0), (
                sub, f, np.max(np.abs(want - got)))
